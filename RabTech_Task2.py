print(model_sm.summary())

alpha = 0.05

print("Final Decision")
print("==============")

if pearson_p < alpha:
    print("Reject H₀.")
    print("There is a statistically significant relationship between")
    print("study hours and exam scores.")
else:
    print("Fail to reject H₀.")
    print("There is not enough evidence of a statistically significant")
    print("relationship between study hours and exam scores.")

import matplotlib.pyplot as plt

plt.figure(figsize=(8, 5))

plt.scatter(
    processed_data["study_hours"],
    processed_data["exam_score"]
)

plt.xlabel("Study Hours per Week")
plt.ylabel("Exam Score")
plt.title("Study Hours vs Exam Score")

plt.show()

