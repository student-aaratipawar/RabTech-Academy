print("===========================")

print("ADF Statistic:", round(adf_diff[0], 4))
print("p-value:", adf_diff[1])

if adf_diff[1] < 0.05:
    print("\nConclusion: Differenced series is stationary.")
else:
    print("\nConclusion: Differenced series is still non-stationary.")

