"""## Augmented Dickey-Fuller (ADF) Test

The ADF test checks whether a time series is stationary.

### Hypotheses

H₀: The time series has a unit root and is non-stationary.

H₁: The time series is stationary.

### Decision Rule

If p-value < 0.05:
Reject H₀ → series is stationary.

If p-value ≥ 0.05:
Fail to reject H₀ → series is non-stationary.
"""

# ADF test

adf_result = adfuller(df["demand"])

print("Augmented Dickey-Fuller Test")
print("===========================")

print("ADF Statistic:", round(adf_result[0], 4))
print("p-value:", adf_result[1])

print("\nCritical Values:")

for key, value in adf_result[4].items():
    print(f"{key}: {value:.4f}")

if adf_result[1] < 0.05:
    print("\nConclusion: The series is stationary.")
else:
    print("\nConclusion: The series is non-stationary.")

# First-order differencing

df["demand_diff"] = df["demand"].diff()

display(df[["demand", "demand_diff"]].head(10))

# ADF test after differencing

