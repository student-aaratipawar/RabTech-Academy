"""## Time-Series Decomposition

Time-series decomposition separates the observed series into:

1. Trend – long-term movement.
2. Seasonality – repeating pattern.
3. Residual – random/unexplained variation.

Since the data is daily, a period of 7 is used to represent a possible weekly seasonal pattern.
"""

